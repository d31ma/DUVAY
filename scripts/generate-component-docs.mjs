#!/usr/bin/env bun
/* Generate API reference fallbacks and filesystem pages for every registered
 * DuVay custom element. Hand-authored API blocks remain authoritative; this
 * inventory fills missing elements and attributes from the component source
 * plus Vuetify's pinned metadata snapshot. */

import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { API_DATA } from '../website/client/shared/scripts/api-data.js';
import { GENERATED_PAGE_INDEX as PRIOR_GENERATED_PAGE_INDEX } from '../website/client/shared/scripts/generated-api-data.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const componentDir = join(root, 'src/components');
const outputFile = join(root, 'website/client/shared/scripts/generated-api-data.js');
const pagesDir = join(root, 'website/client/pages');
const metadata = JSON.parse(await readFile(join(root, 'scripts/data/vuetify-attributes.json'), 'utf8'));
const COMMON = [
  'active-color', 'base-color', 'bg-color', 'border', 'class', 'color', 'density',
  'disabled', 'elevation', 'height', 'hover-elevation', 'id', 'loading', 'location',
  'max-height', 'max-width', 'min-height', 'min-width', 'position', 'readonly',
  'role', 'rounded', 'style', 'tabindex', 'theme', 'tile', 'width',
];

const routeByTag = new Map();
const priorGeneratedRoutes = new Set(PRIOR_GENERATED_PAGE_INDEX.map((page) => page.path));
for (const [route, blocks] of Object.entries(API_DATA)) {
  if (priorGeneratedRoutes.has(route)) continue;
  for (const block of blocks) if (!routeByTag.has(block.tag)) routeByTag.set(block.tag, route);
}

const inventory = await readComponents();
const metaByTag = readMetadata();
const generated = {};
const pageIndex = [];

for (const [tag, entry] of [...inventory].sort(([a], [b]) => a.localeCompare(b))) {
  const route = routeByTag.get(tag) || `/docs/components/${tag.slice(2)}`;
  const existing = routeByTag.has(tag);
  const attrs = [...entry.attrs].sort();
  const meta = metaByTag.get(tag) || new Map();
  const block = {
    tag,
    attributes: attrs.map((name) => {
      const detail = meta.get(name);
      return [name, cleanType(detail?.type) || inferredType(name), '—', cleanDescription(detail?.description) || `Sets the ${name} option.`];
    }),
  };
  if (!existing) block.slots = [['default', 'Component content.']];
  if (!generated[route]) generated[route] = [];
  generated[route].push(block);
  if (!routeByTag.has(tag)) {
    pageIndex.push({ path: route, title: title(tag), group: 'Components', keywords: `${tag} component api attributes` });
    await ensurePage(route, tag);
  }
}

const banner = `/* Generated by scripts/generate-component-docs.mjs. Do not edit manually. */\n`;
const body = banner
  + `export const GENERATED_API_DATA = ${JSON.stringify(generated, null, 2)};\n\n`
  + `export const GENERATED_PAGE_INDEX = ${JSON.stringify(pageIndex, null, 2)};\n`;
await writeFile(outputFile, body);
console.log(`generated ${Object.keys(generated).length} API routes and ${pageIndex.length} fallback pages`);

async function readComponents() {
  const files = (await readdir(componentDir)).filter((name) => name.endsWith('.js'));
  const classes = new Map();
  const tags = new Map();
  for (const file of files) {
    const source = await readFile(join(componentDir, file), 'utf8');
    for (const match of source.matchAll(/(?:export\s+)?class\s+(\w+)\s+extends\s+(\w+)/g)) {
      classes.set(match[1], { parent: match[2], attrs: attrsIn(classBody(source, match.index)) });
    }
    for (const match of source.matchAll(/customElements\.define\(\s*'([\w-]+)'\s*,\s*(\w+)/g)) tags.set(match[1], match[2]);
  }
  const inherited = (name, seen = new Set()) => {
    if (!name || seen.has(name)) return new Set();
    seen.add(name);
    const entry = classes.get(name);
    return entry ? new Set([...entry.attrs, ...inherited(entry.parent, seen)]) : new Set();
  };
  return new Map([...tags].map(([tag, className]) => [tag, { className, attrs: new Set([...inherited(className), ...COMMON]) }]));
}

function classBody(source, classIndex) {
  const open = source.indexOf('{', classIndex);
  if (open < 0) return '';
  let depth = 0;
  let quote = '';
  let lineComment = false;
  let blockComment = false;
  let escaped = false;
  for (let index = open; index < source.length; index += 1) {
    const char = source[index];
    const next = source[index + 1];
    if (lineComment) {
      if (char === '\n') lineComment = false;
      continue;
    }
    if (blockComment) {
      if (char === '*' && next === '/') { blockComment = false; index += 1; }
      continue;
    }
    if (quote) {
      if (escaped) { escaped = false; continue; }
      if (char === '\\') { escaped = true; continue; }
      if (char === quote) quote = '';
      continue;
    }
    if (char === '/' && next === '/') { lineComment = true; index += 1; continue; }
    if (char === '/' && next === '*') { blockComment = true; index += 1; continue; }
    if (char === "'" || char === '"' || char === '`') { quote = char; continue; }
    if (char === '{') depth += 1;
    if (char === '}') {
      depth -= 1;
      if (depth === 0) return source.slice(open + 1, index);
    }
  }
  return source.slice(open + 1);
}

function attrsIn(body) {
  const attrs = new Set();
  const declared = /static\s+attrs\s*=\s*\[([\s\S]*?)\]/.exec(body);
  if (declared) for (const match of declared[1].matchAll(/'([^']+)'/g)) attrs.add(match[1]);
  const readers = [
    /this\._attr\(\s*'([^']+)'/g, /this\._bool\(\s*'([^']+)'/g,
    /this\.(?:getAttribute|hasAttribute)\(\s*'([^']+)'/g,
  ];
  for (const pattern of readers) for (const match of body.matchAll(pattern)) attrs.add(match[1]);
  return attrs;
}

function readMetadata() {
  const result = new Map();
  for (const [key, detail] of Object.entries(metadata)) {
    const slash = key.indexOf('/');
    const component = key.slice(0, slash);
    const tag = `w-${component.replace(/^V/, '').replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase()}`;
    if (!result.has(tag)) result.set(tag, new Map());
    result.get(tag).set(key.slice(slash + 1), detail);
  }
  return result;
}

function cleanType(value = '') {
  return String(value).replace(/<a[^>]*>(.*?)<\/a>/g, '$1').replace(/\s+/g, ' ').trim().slice(0, 180);
}

function cleanDescription(value = '') {
  return String(value).replace(/<[^>]+>/g, '').replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
}

function inferredType(name) {
  if (/^(?:active|absolute|autofocus|border|clearable|disabled|eager|flat|hide-|hover|indeterminate|loading|multiple|open|persistent|readonly|required|reverse|rounded|tile|vertical)/.test(name)) return 'boolean | string';
  return 'string | number | boolean';
}

function title(tag) {
  return tag.slice(2).split('-').map((word) => word[0].toUpperCase() + word.slice(1)).join(' ');
}

async function ensurePage(route, tag) {
  const file = join(pagesDir, route.replace(/^\//, ''), 'tac.html');
  try { await stat(file); return; } catch {}
  await mkdir(dirname(file), { recursive: true });
  const label = title(tag);
  const html = `<h1>${label}</h1>\n<p><code>&lt;${tag}&gt;</code> is part of DuVay's Vuetify-compatible Light-DOM component set.</p>\n\n<h2>Example</h2>\n<demo-compare>\n  <div slot="css"><div class="${tag}">${label}</div></div>\n  <div slot="wc"><${tag}>${label}</${tag}></div>\n</demo-compare>\n`;
  await writeFile(file, html);
}
